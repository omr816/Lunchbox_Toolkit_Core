--[[--------------------------------------------------------------------------
    Lunchbox Toolkit — TalentOverrides
    Hand corrections to the generated talent pack, applied once at load.

    `TalentValues.lua` is generated by `tools/gen_talentvalues.lua` and says "do
    not edit by hand"; re-running the generator rewrites it wholesale. Every hand
    correction therefore lives here, where regenerating the pack cannot lose it.
    Loaded immediately after TalentValues.lua, before TalentValuation.lua reads
    the pack.

    Source for every number: `_docs\leveling-2026-11-04\LEVELING-SHAMAN-WORK-ORDER.md`
    item L-2 and `SHAMAN-ENHANCE-STAT-THEORYCRAFT.md` section 6.1. Nothing here is
    measured in game; the statements say what they are.
--------------------------------------------------------------------------]]

local LT = LunchboxToolkit

local Overrides = {}
LT.TalentOverrides = Overrides

Overrides.VERSION = "1.0.0"

-- Every correction below, with the reason, so a later reader can tell an
-- authored value from a generated one.
Overrides.applied = {}

local function note(what, why)
    Overrides.applied[#Overrides.applied + 1] = { what = what, why = why }
end

local function findTalent(classToken, name)
    local classes = LT.TalentValues and LT.TalentValues.classes
    local class = type(classes) == "table" and classes[classToken] or nil
    if type(class) ~= "table" or type(class.trees) ~= "table" then return nil end
    for _, tree in ipairs(class.trees) do
        for _, talent in ipairs((type(tree) == "table" and tree.talents) or {}) do
            if type(talent) == "table" and talent.name == name then return talent end
        end
    end
    return nil
end

local function patch(talent, fields, what, why)
    if type(talent) ~= "table" then return false end
    for key, value in pairs(fields) do talent[key] = value end
    note(what, why)
    return true
end

-- 1. Enhancement Intellect.
--    Generated value: 0.02 EP. One Intellect is 1.5 attack power at Mental
--    Dexterity 3/3, which on the attack-power scale (attackPower = 1.00) is 1.5
--    before its mana value; Strength is 2.29 and must stay above it. 2.00 is
--    that derivation rounded, so Intellect is level with Strength in practice
--    without overtaking it. PROVISIONAL until M-2 measures the pair.
do
    local ep = type(LT.TalentValues.ForeverEP) == "table"
        and LT.TalentValues.ForeverEP.SHAMAN or nil
    local enhancement = type(ep) == "table" and ep[263] or nil
    if type(enhancement) == "table" then
        enhancement.intellect = 2.00
        note("ForeverEP.SHAMAN[263].intellect = 2.00 (was 0.02)",
            "1 Int = 1.5 AP at Mental Dexterity 3/3; Strength 2.29 stays above it (theorycraft 6.1)")
    end
end

-- 2. Ancestral Knowledge resolves to Intellect.
--    `kind = "primary"` resolved to the class's melee primary (Strength), so a
--    talent that says "Increases your Intellect" was scored as Strength. The
--    row now carries an explicit stat, which TalentValuation honours.
patch(findTalent("SHAMAN", "Ancestral Knowledge"),
    { stat = "intellect" },
    "Ancestral Knowledge -> stat = intellect",
    "the talent's own text says Intellect; `primary` was resolving to Strength (F-3)")

-- 3. One-point abilities with no rank tooltip.
--    These scored 0.001 and sank below every passive. Each number is authored,
--    not measured, and is anchored to one rank of Thundering Strikes, which the
--    harness scores at 16.74 EP (1% crit x crit EP 16.74). A talent worth more
--    than "1% crit" is written as a multiple of that:
--      Stormstrike         50.0  (3x)  150% weapon damage on a 6 s cooldown -
--                                      the build's first goal, so it must rank
--                                      first when it becomes available at 25
--      Water Shield        33.0  (2x)  2% mana per block - the guide's mana fix
--      Rage of the Farseer 25.0  (1.5x) 25 s of extra damage, 3 min cooldown
--      Shamanistic Focus   17.0  (1x)  shocks cost 60% less mana
--    The scorer uses an authored score as written and never multiplies it by the
--    ability-scope factor, because the author already accounted for the scope.
local AUTHORED = "work order L-2(b): anchored to one rank of Thundering Strikes (16.74 EP); not measured"

patch(findTalent("SHAMAN", "Stormstrike"),
    { score = 50.0, scoreWhy = "150% weapon damage on a 6 s cooldown" },
    "Stormstrike score = 50.0", AUTHORED)
patch(findTalent("SHAMAN", "Water Shield"),
    { score = 33.0, scoreWhy = "2% mana per block; the point that solves mana" },
    "Water Shield score = 33.0", AUTHORED)
patch(findTalent("SHAMAN", "Rage of the Farseer"),
    { score = 25.0, scoreWhy = "25 s of extra damage on a 3 min cooldown" },
    "Rage of the Farseer score = 25.0", AUTHORED)
patch(findTalent("SHAMAN", "Shamanistic Focus"),
    { score = 17.0, scoreWhy = "shocks cost 60% less mana" },
    "Shamanistic Focus score = 17.0", AUTHORED)

-- Readable from `/lt diag`-style output and from the capture.
function Overrides:Report()
    for _, entry in ipairs(self.applied) do
        LT:Print("  talent override: " .. tostring(entry.what) .. " — " .. tostring(entry.why))
    end
    if #self.applied == 0 then
        LT:Print("  talent overrides: none applied (TalentValues shape changed?)")
    end
end
